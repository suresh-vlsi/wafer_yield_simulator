`timescale 1ns/1ps

module mips32_program_tb;

    mips32_datapath DUT();


    // =========================================================
    // CLOCK
    // =========================================================

    initial begin

        DUT.clk = 1'b0;

        forever #5 DUT.clk = ~DUT.clk;

    end


    // =========================================================
    // PROGRAM TEST
    // =========================================================

    initial begin

        // -----------------------------------------------------
        // RESET
        // -----------------------------------------------------

        DUT.reset = 1'b1;

        #10;

        DUT.reset = 1'b0;


        // -----------------------------------------------------
        // Initialize $t1 = 50
        // -----------------------------------------------------

        DUT.REGFILE.registers[9] = 32'd50;


        // -----------------------------------------------------
        // Instruction 1
        //
        // ADDI $t0,$t1,100
        //
        // $t0 = 50 + 100 = 150
        // -----------------------------------------------------

        #10;

        $display("");
        $display("==========================================");
        $display("After ADDI");
        $display("$t0 = %d",
                 DUT.REGFILE.registers[8]);


        // -----------------------------------------------------
        // Instruction 2
        //
        // ADD $t2,$t0,$t1
        //
        // $t2 = 150 + 50 = 200
        // -----------------------------------------------------

        #10;

        $display("");
        $display("==========================================");
        $display("After ADD");
        $display("$t0 = %d",
                 DUT.REGFILE.registers[8]);

        $display("$t2 = %d",
                 DUT.REGFILE.registers[10]);


        // -----------------------------------------------------
        // Instruction 3
        //
        // SUB $t3,$t2,$t1
        //
        // $t3 = 200 - 50 = 150
        // -----------------------------------------------------

        #10;

        $display("");
        $display("==========================================");
        $display("After SUB");

        $display("$t0 = %d",
                 DUT.REGFILE.registers[8]);

        $display("$t2 = %d",
                 DUT.REGFILE.registers[10]);

        $display("$t3 = %d",
                 DUT.REGFILE.registers[11]);

        $display("==========================================");


        #10;

        $finish;

    end

endmodule