module mips32_instruction_memory (
    input  [31:0] address,
    output [31:0] instruction
);

    reg [31:0] memory [0:255];

    initial begin

        // =====================================================
        // BASIC VALUES
        // =====================================================

        // R8 = 5
        memory[0]  = 32'h20080005;

        // R9 = 3
        memory[1]  = 32'h20090003;


        // =====================================================
        // R-TYPE ALU
        // =====================================================

        // ADD R10,R8,R9 = 8
        memory[2]  = 32'h01095020;

        // SUB R11,R8,R9 = 2
        memory[3]  = 32'h01095822;

        // AND R12,R8,R9 = 1
        memory[4]  = 32'h01096024;

        // OR R13,R8,R9 = 7
        memory[5]  = 32'h01096825;

        // XOR R14,R8,R9 = 6
        memory[6]  = 32'h01097026;

        // NOR R15,R8,R9 = FFFFFFF8
        memory[7]  = 32'h01097827;

        // SLT R16,R8,R9 = 0
        memory[8]  = 32'h0109802A;


        // =====================================================
        // IMMEDIATE INSTRUCTIONS
        // =====================================================

        // ANDI R17,R8,3 = 1
        memory[9]  = 32'h31110003;

        // ORI R18,R8,8 = 13
        memory[10] = 32'h35120008;

        // XORI R19,R8,15 = 10
        memory[11] = 32'h3913000F;

        // SLTI R20,R9,5 = 1
        memory[12] = 32'h29340005;


        // =====================================================
        // SHIFTS
        // =====================================================

        // SLL R21,R9,2 = 12
        memory[13] = 32'h0009A880;

        // SRL R22,R9,1 = 1
        memory[14] = 32'h0009B042;

        // R24 = -8
        memory[15] = 32'h2018FFF8;

        // SRA R25,R24,2 = -2
        memory[16] = 32'h0018C883;


        // =====================================================
        // LUI
        // =====================================================

        // R26 = 0x12340000
        memory[17] = 32'h3C1A1234;


        // =====================================================
        // STORE / LOAD
        // =====================================================

        // SW R10,100(R0)
        memory[18] = 32'hAC0A0064;

        // LW R27,100(R0)
        memory[19] = 32'h8C1B0064;


        // =====================================================
        // BEQ
        // =====================================================

        // R10 == R27
        // branch to instruction 22
        memory[20] = 32'h114B0001;

        // SHOULD BE SKIPPED
        memory[21] = 32'h201C006F;

        // R28 = 222
        memory[22] = 32'h201C00DE;


        // =====================================================
        // BNE
        // =====================================================

        // R8 != R9
        // branch to instruction 25
        memory[23] = 32'h15090001;

        // SHOULD BE SKIPPED
        memory[24] = 32'h201D006F;

        // R29 = 333
        memory[25] = 32'h201D014D;


        // =====================================================
        // JAL
        // =====================================================

        // JAL instruction 29
        // $ra = PC + 4 = 108
        memory[26] = 32'h0C00001D;


        // Return point
        // Jump to end
        memory[27] = 32'h0800001F;


        // NOP
        memory[28] = 32'h00000000;


        // =====================================================
        // SUBROUTINE
        // =====================================================

        // R23 = 555
        memory[29] = 32'h2017022B;

        // JR $ra
        memory[30] = 32'h03E00008;


        // =====================================================
        // END
        // =====================================================

        memory[31] = 32'h00000000;

    end


    assign instruction =
        memory[address[9:2]];

endmodule